def pre_labeling(text):
    text = str(text).lower()
    score = 0

    # 1. Indikator Promosi Judi Online UMUM (Skor +3)
    # Ditambahkan 'gcr' (gacor), 'scater', 'petir', dll
    judi_umum = [
        'slot', 'judi', 'kasino', 'togel', 'bet', 'depo', 'deposit',
        'wd', 'withdraw', 'maxwin', 'scatter', 'scater', 'gacor',
        'gcr', 'jp', 'cuan', 'pola', 'kakek'
    ]

    # 2. Indikator Promosi Judi Online KERAS/EKSPLISIT (Skor +6 - Langsung Vonis!)
    # Ditambahkan kode angka, nama game populer, dan frasa ajakan
    judi_keras = [
        '303', '138', '888', '777', '88', '69',
        'rtp', 'zeus', 'mahjong', 'olympus', 'pragmatic',
        'main di', 'daftar di', 'link di bio', 'link dibio',
        'klik link', 'tele', 'telegram', 'admin slot'
    ]

    # 3. Indikator Promosi Non-Judi (Skor +2)
    promo_non_judi = ['jual', 'order', 'murah', 'promo', 'diskon', 'open po', 'follow', 'subscribe', 'keranjang kuning', 'cek profil']

    # 4. Indikator Penyangkal (Skor -4)
    penyangkal = ['jangan main', 'rugi', 'awas', 'bahaya', 'haram', 'dampak buruk', 'berhenti']

    # --- PROSES PERHITUNGAN SKOR ---
    for word in judi_umum:
        if word in text: score += 3  # Naikkan bobot umum jadi 3

    for word in judi_keras:
        if word in text: score += 6  # Bobot 6 langsung otomatis memenuhi syarat

    for word in promo_non_judi:
        if word in text: score += 2

    for word in penyangkal:
        if word in text: score -= 4

    # --- LOGIKA PENENTUAN LABEL ---
    if score >= 6:
        return 'Promosi Judi Online'
    elif 2 <= score <= 5:
        # Jika skornya cuma 3 (karena cuma ada kata 'cuan' atau 'gacor')
        # tapi tidak ada kata promosi jualan, masukkan ke Judi Online.
        if any(j in text for j in judi_umum) and not any(p in text for p in promo_non_judi):
            return 'Promosi Judi Online'
        return 'Promosi Non Judi Online'
    else:
        return 'Komentar Normal'

