# Kamus Normalisasi (Tambahkan sesuai kebutuhan dataset Anda)
norm_dict = {
    "gk": "tidak", "yg": "yang", "dm": "pesan",
    "bgt": "banget", "gacorr": "gacor", "jp": "jackpot"
}

def text_preprocessing(text):
    text = str(text).lower() # Case Folding

    # Data Cleaning
    text = re.sub(r'http\S+|www\S+|https\S+', '', text, flags=re.MULTILINE) # URL
    text = re.sub(r'@\w+', '', text) # Mention
    text = re.sub(r'#\w+', '', text) # Hashtag

    # PERUBAHAN PENTING: Tambahkan 0-9 agar angka tidak terhapus
    text = re.sub(r'[^a-zA-Z0-9\s]', ' ', text)

    text = re.sub(r'\s+', ' ', text).strip() # Hapus spasi ganda

    # Normalisasi Kata
    words = text.split()
    normalized_words = [norm_dict[word] if word in norm_dict else word for word in words]
    text = ' '.join(normalized_words)

    # Stopword Removal
    text = stopword_remover.remove(text)

    # Stemming
    text = stemmer.stem(text)

    return text

